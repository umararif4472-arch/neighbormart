// --- Items & Tools -----------------------------------------------------------

ItemListing _item(
  DateTime today, {
  required String id,
  required String ownerId,
  required String title,
  required String description,
  required String category,
  required String condition,
  ListingStatus status = ListingStatus.active,
  required int maxDurationDays,
  int? depositAmount,
  int? dailyFee,
  required int listedDaysAgo,
  int views = 0,
  String pickupPreference = 'either',
  String pickupInstructions = 'Message me and we will sort a time.',
}) {
  final created = today.subtract(Duration(days: listedDaysAgo));
  final isRent = dailyFee != null;
  return ItemListing(
    id: id,
    ownerId: ownerId,
    listingType: isRent ? ListingType.rent : ListingType.borrow,
    title: title,
    description: description,
    price: dailyFee ?? 0,
    priceUnit: isRent ? PriceUnit.day : PriceUnit.fixed,
    location: _ownerAreas[ownerId]!,
    status: status,
    createdAt: created,
    updatedAt: created,
    views: views,
    details: ItemListingDetails(
      category: category,
      condition: condition,
      depositAmount: depositAmount,
      maxDurationDays: maxDurationDays,
      pickupPreference: pickupPreference,
      pickupInstructions: pickupInstructions,
    ),
  );
}

