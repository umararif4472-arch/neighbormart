DateTime _daysFromNow(int offset) {
  final now = DateTime.now();
  return DateTime(now.year, now.month, now.day).add(Duration(days: offset));
}

DateTime _hoursAgo(int h) => DateTime.now().subtract(Duration(hours: h));

UserBadge _badge(String id, String label, String desc, int daysAgo) =>
    UserBadge(
      id: id,
      label: label,
      description: desc,
      earnedAt: _daysFromNow(-daysAgo),
    );

