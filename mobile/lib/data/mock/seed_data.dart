    .map((s) => 'https://picsum.photos/seed/bdb-$s/640/480')
    .toList();

Item _item(
  String id,
  String ownerId,
  String title,
  String desc,
  String cat,
  String cond,
  String avail,
  int maxDays,
  int? deposit,
  int? fee,
  String pickupPref,
  String instructions,
  int listedDaysAgo,
  LatLng loc,
) {
  return Item(
    id: id,
    ownerId: ownerId,
    title: title,
    description: desc,
    category: cat,
    condition: cond,
    photos: _photosFor(id),
    location: loc,
    availability: avail,
    borrowTerms: BorrowTerms(
      maxDurationDays: maxDays,
      depositAmount: deposit,
      dailyFee: fee,
      pickupPreference: pickupPref,
      pickupInstructions: instructions,
    ),
    createdAt: _daysFromNow(-listedDaysAgo),
  );
}

