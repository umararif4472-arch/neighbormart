BorrowRequest _req(
  String id,
  String itemId,
  String borrowerId,
  int startOff,
  int endOff,
  String note,
  String status,
  int createdH, {
  int? respondedH,
  int? returnedH,
  int? offerAmount,
  ArenaSlot? slot,
}) {
  final due =
      (status == 'active' || status == 'returned' || status == 'reviewed')
      ? _daysFromNow(endOff)
      : null;
  return BorrowRequest(
    id: id,
    itemId: itemId,
    borrowerId: borrowerId,
    period: BorrowPeriod(
      start: _daysFromNow(startOff),
      end: _daysFromNow(endOff),
    ),
    note: note,
    status: status,
    offerAmount: offerAmount,
    slot: slot,
    createdAt: _hoursAgo(createdH),
    respondedAt: respondedH != null ? _hoursAgo(respondedH) : null,
    dueAt: due,
    returnedAt: returnedH != null ? _hoursAgo(returnedH) : null,
  );
}

String _slotDate(int dayOffset) {
  final d = _daysFromNow(dayOffset);
  String pad(int n) => n.toString().padLeft(2, '0');
  return '${d.year}-${pad(d.month)}-${pad(d.day)}';
}

